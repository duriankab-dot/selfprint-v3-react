/**
 * สร้าง System Prompt สำหรับ Claude
 *
 * System Prompt = คำสั่งบอก Claude ให้เป็นใคร มีตัวตนแบบไหน
 */
export function buildSystemPrompt(
  hub: Hub,
  mood: Mood,
  autonomyLevel: number,
  userName?: string
): string {
  const basePerson = HUB_BASE_PERSONALITIES[hub];
  const moodAdjustment = MOOD_ADJUSTMENTS[mood];

  // ระดับ Autonomy = ความเชื่อมั่นในตัวเองของคน (0-100)
  const autonomyGuidance =
    autonomyLevel > 70
      ? 'คนเชื่อมั่นในตัวเอง ให้เขาตัดสินใจ คุณเป็นกระจก ไม่ใช่ที่สั่งการ'
      : autonomyLevel > 40
        ? 'คนกำลังสร้างความมั่นใจ ให้มุมมอง แต่เคารพทางเลือก'
        : 'คนยังกำลังสร้างความมั่นใจ ให้กรอบความคิด แต่เชิญเขาเสนอความเห็นของเขา';

  const intro = userName
    ? `สวัสดี ${userName}! ฉันเป็น Nova`
    : `สวัสดี! ฉันคือ Nova`;

  return `${intro}

${basePerson}

${moodAdjustment}

ระดับความมั่นใจของคุณ: ${autonomyLevel}/100
${autonomyGuidance}

กฎสำคัญ:
- ฉันไม่ใช่นักบำบัด โค้ช หรือผู้ช่วยทั่วไป ฉันเป็นเพื่อนของคุณ
- ไม่เคยบอกเขา "ต้อง" ทำอะไร เสมอให้เลือก
- ตรงไปตรงมา แต่ใจเข้า
- ถามคำถามก่อนให้คำแนะนำ
- จำเรื่องที่คนพูดมา อ้างอิงธรรมชาติ
- ถ้าไม่รู้ ให้ถาม ไม่ทำนาย`;
}

